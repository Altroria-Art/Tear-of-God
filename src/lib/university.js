// รหัสรุ่น/ปีเข้าศึกษา: ค่าต่ำสุดคงที่ 38 (พ.ศ. 2538)
export const ADMISSION_YEAR_MIN = 38;

// ปี ป.ร. ขึ้นกับวันที่ปัจจุบัน → ปีหน้าเด้งขึ้นเองโดยไม่ต้องแก้ไฟล์ (ปี 2026 = 69)
export function getCurrentAdmissionYear(date = new Date()) {
  return (date.getFullYear() + 543) % 100;
}

export function getAdmissionYears(date = new Date()) {
  const max = getCurrentAdmissionYear(date);
  const years = [];
  for (let y = ADMISSION_YEAR_MIN; y <= max; y += 1) years.push(String(y));
  return years;
}

export function getFacultyByName(name) {
  return FACULTIES.find((f) => f.name === name);
}

export function getMajorsForFaculty(name) {
  const faculty = getFacultyByName(name);
  return faculty ? faculty.majors : [];
}

export function isValidFacultyMajor(faculty, major) {
  const facultyObj = getFacultyByName(faculty);
  return !!facultyObj && facultyObj.majors.includes(major);
}

export function isValidAdmissionYear(year, date = new Date()) {
  const n = Number(year);
  return Number.isInteger(n) && n >= ADMISSION_YEAR_MIN && n <= getCurrentAdmissionYear(date);
}